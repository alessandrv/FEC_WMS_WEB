-- ============================================================
-- Warehouse map shared by every page (Deposito, Prelievi, Trasferimenti,
-- Visualizza magazzino, Ispezione) and edited from "Editor mappa".
-- Each save inserts a new version: the latest row is the map in use, the
-- older rows are the history. The map never touches wms_items: removing a
-- shelf with packages only lists those locations as "outside the map".
-- ============================================================

CREATE TABLE wms_map_layout (
    id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layout      CLOB NOT NULL,       -- JSON {"pages": [{page, title, rows, cols, sections: [...]}]}
    created_at  DATE DEFAULT SYSDATE,
    created_by  VARCHAR2(50),
    note        VARCHAR2(255)
);
