-- ============================================================
-- Inventory counts entered from the "Inventario" page (replaces the Excel file).
-- One row per count: article, movement, location, quantity, who (IP) and when.
-- The rows never touch wms_items; they are exported to Excel from the page.
-- id_mov uses the wms_items.id_mov format: ADAPTA number ('83754') or
-- Skyline document 'ANNO/TIPO/NUMERO' ('2026/CA/48').
-- ============================================================

CREATE TABLE wms_inventario (
    id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ins_ts      DATE DEFAULT SYSDATE NOT NULL,
    id_art      VARCHAR2(20) NOT NULL,
    id_mov      VARCHAR2(30),
    area        VARCHAR2(2)  NOT NULL,
    scaffale    VARCHAR2(2)  NOT NULL,
    colonna     VARCHAR2(3)  NOT NULL,
    piano       VARCHAR2(2)  NOT NULL,
    qta         NUMBER(10)   NOT NULL,
    ip_address  VARCHAR2(50)
);
CREATE INDEX wms_inventario_ts_ix ON wms_inventario (ins_ts);
